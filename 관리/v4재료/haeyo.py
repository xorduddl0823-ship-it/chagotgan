# 표준형 그대로 두는 글 — 로그인 · 오류 안내 (규칙 4-1)
KEEP = re.compile(r"「[^」]*니다」|«[^»]*니다»|[^\"'<>`]*(?:못했습니다|막혔습니다|6자리를 보냈습니다|로그인이 필요합니다)[^\"'<>`]*")

def _iyo(prev):
    """X입니다 → 받침 있으면 X이에요, 없으면 X예요"""
    if prev and "가" <= prev <= "힣":
        return "이에요" if (ord(prev) - 0xAC00) % 28 else "예요"
    return "이에요"

def convert(text):
    """바꾼 글과 함께 [(전, 후)] 를 돌려줍니다"""
    keep = {}
    def hold(m):
        k = "\u0000K%d\u0000" % len(keep); keep[k] = m.group(0); return k
    t = KEEP.sub(hold, text)
    def word(m):
        w = m.group(0)
        if w in WORDS: return WORDS[w]
        if w.endswith("입니다"):
            stem = w[:-3]
            return stem + _iyo(stem[-1] if stem else "")
        return w
    t = re.sub(r"[가-힣]*니다", word, t)
    for k, v in keep.items(): t = t.replace(k, v)
    return t.replace("것이에요", "거예요").replace("가입 코드을", "가입 코드를")
